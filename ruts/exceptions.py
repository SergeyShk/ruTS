class RutsError(Exception):
    """
    Базовое исключение библиотеки

    Описание:
        Все исключения ruTS наследуют его и один из встроенных классов,
        поэтому ловятся как по своему имени, так и по привычному
        ValueError, TypeError, OSError или RuntimeError
    """


class SourceTypeError(RutsError, TypeError):
    """
    Некорректный тип источника данных

    Описание:
        Вместо строки или объекта Doc передано что-то другое, справочник
        частотности не Counter, список текстов не список списков слов,
        путь не строка и не Path, токенизатор не вызываемый объект
    """


class SourceError(RutsError, ValueError):
    """
    Непригодный источник данных

    Описание:
        В источнике нет слов, предложений, текстов или коллокаций, нет
        нужной разметки (разбора зависимостей) или после отсева не
        осталось единиц
    """


class ParameterError(RutsError, ValueError):
    """
    Некорректный параметр

    Описание:
        Порог, окно, размер сегмента или число элементов вне допустимого
        диапазона, неизвестная мера, вариант, пресет, слой, ступень или
        категория набора данных
    """


class UnknownStatError(ParameterError, KeyError):
    """
    Неизвестное название статистики

    Описание:
        Сообщение без кавычек, которые добавляет __str__ у KeyError
    """

    __str__ = Exception.__str__


class DatasetNotFoundError(RutsError, OSError):
    """
    Набор данных не загружен

    Описание:
        Файлы набора отсутствуют в директории данных; текст исключения
        подсказывает команду загрузки
    """


class DataFileError(RutsError, ValueError):
    """
    Файл набора данных не читается

    Описание:
        Файл поврежден, имеет неожиданный формат или не декодируется
        ни в одной из поддерживаемых кодировок
    """


class DownloadError(RutsError, RuntimeError):
    """
    Ошибка загрузки из сети

    Описание:
        Файл не удалось скачать или он не прошел проверку контрольной суммы
        и был удален
    """
